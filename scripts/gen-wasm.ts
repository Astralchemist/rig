import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';

const ROOT = resolve(import.meta.dir, '..');
const OUT = resolve(ROOT, 'packages/core/src/extract/wasm-embedded.ts');

// resolve from packages/core where web-tree-sitter + tree-sitter-wasms are declared
const require = createRequire(resolve(ROOT, 'packages/core/package.json'));
const wtsRoot = dirname(require.resolve('web-tree-sitter'));

const SOURCES: Record<string, string> = {
  runtime: resolve(wtsRoot, 'tree-sitter.wasm'),
  typescript: require.resolve('tree-sitter-wasms/out/tree-sitter-typescript.wasm'),
  tsx: require.resolve('tree-sitter-wasms/out/tree-sitter-tsx.wasm'),
  javascript: require.resolve('tree-sitter-wasms/out/tree-sitter-javascript.wasm'),
  python: require.resolve('tree-sitter-wasms/out/tree-sitter-python.wasm'),
};

const lines: string[] = [
  '// AUTO-GENERATED by scripts/gen-wasm.ts — do not edit.',
  '// Regenerate with `bun run gen:wasm`. Gitignored; derived from package.json deps.',
  '',
  'const decode = (b64: string): Uint8Array => {',
  '  const bin = atob(b64);',
  '  const out = new Uint8Array(bin.length);',
  '  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);',
  '  return out;',
  '};',
  '',
];

let total = 0;
for (const [name, path] of Object.entries(SOURCES)) {
  const bytes = await readFile(path);
  total += bytes.byteLength;
  lines.push(`export const ${name}: Uint8Array = decode(${JSON.stringify(bytes.toString('base64'))});`);
}

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, lines.join('\n') + '\n');
console.log(`✓ wrote ${OUT} (${(total / 1024 / 1024).toFixed(2)} MB raw wasm)`);
