// Shapes shared by the bench harness: queries.json, the results file, and the
// tool definitions each arm hands the model.

// Anthropic-style tool definition; the OpenRouter provider converts it to the
// OpenAI function shape on the way out.
export interface ToolDef {
  name: string;
  description: string;
  input_schema: Record<string, unknown>;
}

export type ArmName = 'baseline' | 'rig' | 'rig-search' | 'grep+rig' | 'grep+rig+map';
export type ProviderName = 'openrouter' | 'anthropic';

// A pattern is a case-insensitive substring, or a regex written "/source/flags".
export type Pattern = string;

export interface Expected {
  // Every pattern must match.
  all?: Pattern[];
  // At least `any_min` (default 1) of these must match.
  any?: Pattern[];
  any_min?: number;
  // None of these may match.
  none?: Pattern[];
}

export interface Query {
  id: string;
  // 'lookup' names the symbol or file; 'natural' is phrased the way a user
  // asks, with no identifiers, so it measures search rather than grep.
  category: 'lookup' | 'natural';
  ask: string;
  // Short reference answer at the pinned commit; the LLM judge sees it.
  reference: string;
  expected: Expected;
}

export interface QueriesFile {
  target: { repo: string; url: string; commit: string; tag?: string };
  queries: Query[];
}

export interface CheckResult {
  pass: boolean;
  missing: string[];
  any_matched: string[];
  forbidden: string[];
}

export interface JudgeResult {
  verdict: 'correct' | 'incorrect' | 'error';
  reason: string;
  cost_usd: number | null;
  prompt_tokens: number;
  completion_tokens: number;
}

export type StopReason = 'answer' | 'turn_limit' | 'error';

export interface RunResult {
  query_id: string;
  arm: ArmName;
  trial: number;
  prompt_tokens: number;
  completion_tokens: number;
  // USD. OpenRouter reports it per call; on the Anthropic path it is computed
  // from list prices. null when any call's cost is unknown.
  cost_usd: number | null;
  model_calls: number;
  tool_turns: number;
  // Characters of tool output fed back to the model, per tool name.
  tool_chars: Record<string, number>;
  stop: StopReason;
  final_text: string;
  error?: string;
  resolved_models: string[];
  upstreams: string[];
  elapsed_ms: number;
  check: CheckResult;
  judge?: JudgeResult;
}

export interface RigVersion {
  version: string;
  commit: string | null;
  dirty: boolean;
  // Hash of the rig sources that shape indexing and the tool surface.
  fingerprint: string;
}

// The repository overview the grep+rig+map arm puts in its system prompt:
// rig's orientation map of the target, generated by this checkout's rig.
export interface OverviewInfo {
  budget_tokens: number;
  chars: number;
  // chars / 4, the estimate the map's budget is enforced with.
  est_tokens: number;
  // Generation time (0 when it came from the index's cache).
  elapsed_ms: number;
  cached: boolean;
  generated_at: string;
}

export interface BenchFile {
  schema: 2;
  label: string;
  started_at: string;
  finished_at: string | null;
  provider: ProviderName;
  model: string;
  judge_model: string | null;
  rig: RigVersion;
  target: {
    repo: string;
    commit: string | null;
    expected_commit: string;
    index: { nodes: number; files: number; rebuilt: boolean; elapsed_ms: number };
  };
  arms: ArmName[];
  // Present when the grep+rig+map arm ran.
  overview?: OverviewInfo;
  trials: number;
  max_turns: number;
  queries: Query[];
  results: RunResult[];
}

// ------------------------------------------------- multi-session memory mode

// memory-off, memory-on and oracle are the measured arms; grep-only is the
// sanity check that the session-2 answers are not in the code; memory-auto is
// memory-off's session 1 plus automatic capture and the SessionStart brief.
export type MemoryArmName = 'memory-off' | 'memory-on' | 'oracle' | 'grep-only' | 'memory-auto';

export interface SessionExpected extends Expected {
  // Trap answers: what the code alone points to. Any match fails the check.
  must_not?: Pattern[];
}

export interface SessionCheck extends CheckResult {
  // must_not patterns the answer matched.
  trapped: string[];
  // Whether the answer had the marker line the criteria are scoped to.
  marker_found: boolean;
}

// What session 1 establishes.
export type SessionTaskType = 'decision' | 'constraint' | 'dead-end' | 'discovery';

export interface SessionTask {
  id: string;
  type: SessionTaskType;
  // True when the code alone points to a specific wrong answer, which the
  // session-1 fact overrides; must_not holds that answer.
  trap: boolean;
  // Session 1: fixed user messages, each followed by real model turns.
  session1: string[];
  // Session 2: one user message in a fresh context.
  session2: string;
  // Which task set the pair belongs to: "first" (tasks 1-10, the default
  // when absent) or "confirmation" (tasks 11-20). --task-set selects one.
  set?: string;
  // Trap tasks of the confirmation set: the session-1 fact, as a literal
  // that session 2 must not contain and the target's code must not either.
  secret?: string;
  // The oracle arm's reference summary of what session 1 established.
  oracle: string;
  // A model answer to session 2 that passes; a test checks it does.
  reference: string;
  expected: SessionExpected;
  // Trap tasks: where the code points to the trap answer, checked against the
  // target checkout ({file, pattern} with a "/regex/" or substring pattern).
  code_evidence?: { file: string; pattern: Pattern }[];
}

export interface SessionsFile {
  // Marker that starts the line session-2 answers are graded on.
  answer_marker: string;
  tasks: SessionTask[];
}

export interface SessionOutcome {
  session_id: string;
  messages: number;
  prompt_tokens: number;
  completion_tokens: number;
  cost_usd: number | null;
  model_calls: number;
  tool_turns: number;
  tool_calls: Record<string, number>;
  tool_chars: Record<string, number>;
  stop: StopReason;
  stops: StopReason[];
  replies: string[];
  final_text: string;
  error?: string;
  resolved_models: string[];
  upstreams: string[];
  elapsed_ms: number;
}

export interface DroppedWaypoint {
  id: string;
  kind: string;
  title: string;
  summary: string;
}

// One record automatic capture extracted from session 1 (memory-auto).
export interface CapturedRecord {
  // The extractor's kind (agreed, rejected, dead-end, correction, constraint,
  // decision) and the waypoint kind it was stored as.
  kind: string;
  waypoint_kind: string;
  summary: string;
  rationale: string;
  confidence: number;
  // Stored (false: a duplicate of a stored waypoint).
  stored: boolean;
  // Eligible for the SessionStart brief.
  injectable: boolean;
}

// What automatic capture did between session 1 and session 2 (memory-auto).
export interface SessionCapture {
  // Conversation events the pipeline read.
  events: number;
  records: CapturedRecord[];
  // The brief session 2 got, exactly as the SessionStart hook prints it.
  brief: string;
  elapsed_ms: number;
  error?: string;
}

export interface SessionRunResult {
  task_id: string;
  arm: MemoryArmName;
  trial: number;
  // null for the arms that have no session 1 (oracle, grep-only).
  s1: SessionOutcome | null;
  s2: SessionOutcome;
  // Waypoints session 1 left in the trial's database.
  waypoints: DroppedWaypoint[];
  // Session 1's waypoints that a rig_waypoints call in session 2 returned
  // (distinct ids); null when session 2 had no rig_waypoints tool.
  recalled: number | null;
  check: SessionCheck;
  // memory-auto only.
  capture?: SessionCapture;
}

export interface CombinedRun {
  label: string;
  started_at: string;
  rig: RigVersion;
  snapshot_sha256: string;
  tasks: string[];
  trials: number;
}

export interface SessionsBenchFile {
  schema: 1;
  mode: 'sessions';
  // The pre-registered pass bar, verbatim, written before any run.
  preregistered_bar: string;
  // The confirmation rule, verbatim; absent from files written before it.
  confirmation_rule?: string;
  // The memory-auto pre-registration, verbatim; absent from files written
  // before it.
  memory_auto_preregistration?: string;
  // The --task-set the run was limited to, when it was.
  task_set?: string;
  // Set by mergeSessionsFiles: the runs a combined file was built from.
  combined?: CombinedRun[];
  // Set by addArmsToBaseline: arms from a new run judged against stored runs
  // of the baseline arms (same model, trials, bar and target; other builds).
  added_arms?: { arms: MemoryArmName[]; run: string; baseline_runs: string[] };
  label: string;
  started_at: string;
  finished_at: string | null;
  provider: ProviderName;
  model: string;
  rig: RigVersion;
  target: {
    repo: string;
    commit: string | null;
    expected_commit: string;
    // Every trial starts from a copy of this snapshot of the target's index.
    snapshot: { sha256: string; bytes: number; nodes: number; waypoints: number };
  };
  // Where the arms' rig instructions came from: the generated installer
  // instructions, and a hash of that file.
  instructions: { path: string; sha256: string };
  // Trap tasks' code evidence, checked against the target at run time.
  trap_evidence: { task_id: string; file: string; pattern: Pattern; found: boolean }[];
  // Tasks' session-1 secrets, searched for in the target's files at run time;
  // in_code should be false for every one. Absent from older files.
  secret_check?: { task_id: string; secret: string; in_code: boolean }[];
  answer_marker: string;
  arms: MemoryArmName[];
  trials: number;
  max_turns: number;
  tasks: SessionTask[];
  results: SessionRunResult[];
}
